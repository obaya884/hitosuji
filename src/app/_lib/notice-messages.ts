/* ── トースト（変数を含むので関数で持つ） ──────────────────────────── */

/**
 * ルーチン化の完了（F-305 / 画面定義書01 §4.1）。**「明日から展開」を添える**のは、
 * 作成しても当日のリストが変わらないため（開始日は翌日。画面定義書01 §4.1）
 */
export function routinizedMessage(taskName: string): string {
  return `「${taskName}」をルーチン化しました（明日から展開）`;
}

/**
 * バンドルの途中で別のタスクを始めたときの情報通知（F-119 / 画面定義書01 §4.4）。
 * `remaining` は未完了メンバーの件数で、実行中を含む（画面定義書01 §4.4）
 */
export function bundleDepartureMessage(bundleName: string, remaining: number): string {
  return `「${bundleName}」が途中です（残り${remaining}件）`;
}
