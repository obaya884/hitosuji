// 「値が入っていない」ことの示し方（画面定義書00_共通 §2.4）の語彙をここに集める。記号・語・
// 対象外の語まで1か所に置くのは、同じ意味が画面ごとに割れる事故が2度あったため（FB-55 / FB-57）。
// 描き方は持たない（薄色の span は `_components/unset-mark.tsx`）——`format.ts` のような
// 純粋なフォーマッタがコンポーネントに依存しないようにするため。
// **語を足したら `eslint.config.mjs` の `UNSET_WORDS_LOOSE` / `UNSET_WORDS_EXACT` も更新する**
// （直書きを禁止する側のリスト。ただし `id: null` の候補ラベルと空 value の `<option>` は
// 形で縛っているので、リストに無い語を発明した場合もそこで止まる）。

/** 属性（モード・プロジェクト等、マスタを参照する値）の未設定。**一覧のセルだけ**で使う */
export const UNSET_MARK = "-";

/** 時間の値の未設定・未確定。属性とは記号を分ける（§2.4） */
export const UNSET_TIME_MARK = "--:--";

/**
 * 未設定を表す語。属性を未設定に戻す選択肢（ポップオーバーの候補・フォームのセレクト）と、
 * セルの読み上げ（`aria-label`）に使う。**属性名を冠さない**（「モードなし」等にしない）
 */
export const UNSET_LABEL = "未設定";

/** 集計（レビュー §3.5）のグループ行ラベル。語は上と同じで、括弧は行ラベルであることを示す */
export const UNSET_GROUP_LABEL = `（${UNSET_LABEL}）`;

/**
 * セクションが `null` のタスクを束ねるグループの名前。**上の「未設定」に揃えない**——値の不在
 * ではなくインボックスグループの名前なので §2.4 の対象外（画面定義書01 §3.2）。
 * 揃え忘れではないことを示すため、あえてここに並べている
 */
export const UNCATEGORIZED_LABEL = "未分類";
