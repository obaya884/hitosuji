// ブラウザ段（テスト戦略定義書 §3）でだけ使う道具。**コンポーネント段からは呼ばない**。
import { beforeEach } from "vitest";

/**
 * アイコンを実物と同じ小ささに固定する CSS。
 *
 * アイコンの大きさはクラス（`h-3 w-3`）で決まるため、敷かないと素の SVG が既定サイズの置換要素
 * （300x150）として描かれ、それを含む行だけ桁違いに高くなる。**行の並びを測るどのテストでも要る**
 * ので、理由ごとここに1つ置く。クラス名ではなく要素で当てているのは、下の「実物のクラス名で書く」
 * が効かない代わりに**実装が変わっても壊れない**ものだけを対象にしているため（大きさの正しさは
 * 測る対象ではなく、行の高さが現実的であればよい）。
 */
export const ICON_SIZE_CSS = "svg { width: 12px; height: 12px }";

/**
 * 幾何に効くクラスだけを、実物と同じ意味でこの段に敷く。
 *
 * この段にスタイルシートは無い（§3「幾何はインライン style で組む」）。自前の盤面ならそれで足りるが、
 * **実物のコンポーネントを描いて測る**ときは、貼り付き（`sticky`）やパネルのスクロール
 * （`overflow-y-auto`）といった**測る対象そのもの**がクラス側にあるので、当たらないままでは
 * 何も起きない盤面を測ることになる。
 *
 * 敷いてよいのは**それが無いと測れないものだけ**。色・余白・字送りは持ち込まない（測る対象ではなく、
 * 実物の見た目を再現し始めるとスタイルシートを読むのと変わらなくなる）。
 *
 * **測る対象のセレクタは実物のクラス名で書く**——実装がクラスを変えれば当たらなくなり、各テストが
 * 先頭に置く「段の前提」の主張（貼り付いている／スクロールできる）が赤くなって、測れなくなった
 * ことが分かる。例外は `ICON_SIZE_CSS` だけ（理由はそちら）。
 *
 * @param css 実物のクラス名に当てる CSS。テストファイル側に定数で置き、何をなぜ敷くかを書く
 */
export function installGeometryStyles(css: string): void {
  beforeEach(() => {
    const style = document.createElement("style");
    style.textContent = css;
    document.head.append(style);
    return () => style.remove();
  });
}
